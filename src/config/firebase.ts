function _decodeBytes(bytes: number[]): string {
  try {
    const chars = bytes.map((b, i) => String.fromCharCode(b ^ _K_SEED[i % _K_SEED.length] ^ ((i * 11 + 7) & 0xFF)));
    return chars.join('');
  } catch {
    return '';
  }
}

