/**
 * Xona tili bo'yicha tasodifiy matn tanlash funksiyasi
 */
export const getRandomBattleText = (lang: 'uz-latn' | 'uz-cyrl' | 'en' | 'ru' | 'code' | string): string => {
  let pool: string[];

  switch (lang) {
    case 'uz-cyrl':
      pool = BATTLE_TEXTS_UZ_CYRL;
      break;
    case 'en':
      pool = BATTLE_TEXTS_EN;
      break;
    case 'ru':
      pool = BATTLE_TEXTS_RU;
      break;
    case 'code':
      pool = BATTLE_TEXTS_CODE;
      break;
    case 'uz-latn':
    default:
      pool = BATTLE_TEXTS_UZ_LATN;
      break;
  }

  const randomIndex = Math.floor(Math.random() * pool.length);
  return pool[randomIndex];
};
